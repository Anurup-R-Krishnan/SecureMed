import hashlib

def _get_jwt_signing_key(raw_key: str) -> str:
    # Ensure a minimum length for HMAC signing; fall back to a derived key if too short.
    if len(raw_key) >= 32:
        return raw_key
    return hashlib.sha256(raw_key.encode('utf-8')).hexdigest()

